import { describe, expect, it } from 'vitest';
import { generateMarkdown } from './markdown-export';
import { parseMarkdown } from './markdown-import';
import { aBoundedContext, aRelationship } from '../test/builders';

describe('Markdown export/import round-trip', () => {
  it('preserves name, relationship type, roles, notes and clarity (not ids/positions)', () => {
    const billing = aBoundedContext({
      data: { name: 'Billing', description: 'Handles invoices', color: '#3b82f6' },
      position: { x: 500, y: 500 },
    });
    const shipping = aBoundedContext({
      data: { name: 'Shipping', description: '', color: '#10b981' },
      position: { x: 900, y: 900 },
    });
    const relationship = aRelationship({
      source: billing.id,
      target: shipping.id,
      data: {
        relationshipType: 'AnticorruptionLayer',
        sourceRole: 'upstream',
        targetRole: 'downstream',
        notes: 'translation layer needed',
        clarity: 'needs-improvement',
      },
    });

    const markdown = generateMarkdown([billing, shipping], [relationship]);
    const result = parseMarkdown(markdown);

    expect(result.warnings).toEqual([]);
    expect(result.nodes.map((n) => n.data.name).sort()).toEqual(['Billing', 'Shipping']);

    expect(result.edges).toHaveLength(1);
    const importedEdge = result.edges[0];
    expect(importedEdge.data?.relationshipType).toBe('AnticorruptionLayer');
    expect(importedEdge.data?.sourceRole).toBe('upstream');
    expect(importedEdge.data?.targetRole).toBe('downstream');
    expect(importedEdge.data?.notes).toBe('translation layer needed');
    expect(importedEdge.data?.clarity).toBe('needs-improvement');

    const importedBilling = result.nodes.find((n) => n.data.name === 'Billing');
    const importedShipping = result.nodes.find((n) => n.data.name === 'Shipping');
    // Ids and positions are regenerated by markdown import, not preserved.
    expect(importedBilling?.id).not.toBe(billing.id);
    expect(importedShipping?.id).not.toBe(shipping.id);
    expect(importedBilling?.position).not.toEqual(billing.position);
  });
});
